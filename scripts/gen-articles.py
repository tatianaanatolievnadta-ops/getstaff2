    items = []
    for item in faq:
        items.append(
            f"<details><summary>{esc(item['q'])}</summary><p>{esc(item['a'])}</p></details>"
        )
    return (
        "<h2>Частые вопросы</h2>\n"
        '<div class="article-faq">\n'
        + "\n".join(items)
        + "\n</div>\n"
    )


